import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

export interface ChatMessage {
  role: "user" | "assistant" | "system";
  content: string;
}

interface TxnItem {
  id?: string;
  flow?: "in" | "out";
  amount?: number;
  title?: string;
  time?: string;
  kind?: string;
}

interface CsvAuditExpenseItem {
  id?: string;
  invoiceNo?: string;
  expectedAmount?: number;
  currentAmount?: number;
  category?: string;
  note?: string;
  isMissingOrAltered?: boolean;
}

interface CsvAuditContext {
  totalOriginalAmount?: number;
  totalFinalAmount?: number;
  billMistakesTotal?: number;
  businessCommissionsTotal?: number;
  autoGeneratedExpenses?: CsvAuditExpenseItem[];
}

interface RequestPayload {
  prompt?: string;
  query?: string;
  messages?: ChatMessage[];
  inflows?: TxnItem[];
  outflows?: TxnItem[];
  totals?: { in?: number; out?: number };
  contractors?: { name: string; outstanding: number; status?: string }[];
  csvAuditContext?: CsvAuditContext;
}

const PREFERRED_CHAT_MODELS = [
  "qwen/qwen3.8-27b",
  "openai/gpt-oss-120b",
  "openai/gpt-oss-20b",
  "allam-2-7b",
];

function generateLocalForensicReply(userQuery: string, payload: RequestPayload): string {
  const q = userQuery.toLowerCase();
  const totalIn = Number(payload.totals?.in) || 0;
  const totalOut = Number(payload.totals?.out) || 0;
  const netCash = Math.round((totalIn - totalOut) * 100) / 100;
  const inflowsCount = payload.inflows?.length || 0;
  const outflowsCount = payload.outflows?.length || 0;
  const csv = payload.csvAuditContext;
  const missingCommissions = (csv?.autoGeneratedExpenses || []).filter((e) => e.isMissingOrAltered);

  if (
    q.includes("mismatch") ||
    q.includes("difference") ||
    q.includes("gap") ||
    q.includes("discrepancy") ||
    q.includes("reconcil")
  ) {
    const orig = csv?.totalOriginalAmount || totalIn;
    const fin = csv?.totalFinalAmount || totalIn;
    const mist = csv?.billMistakesTotal || 0;
    const comm = csv?.businessCommissionsTotal || 0;

    let text = `### 🔍 Forensic Cash Mismatch Audit\n\n`;
    text += `- **Gross CSV Sales (Before Overrides)**: SAR ${orig.toLocaleString(undefined, { minimumFractionDigits: 2 })}\n`;
    text += `- **Bill Mistakes (Deductions)**: -SAR ${mist.toLocaleString(undefined, { minimumFractionDigits: 2 })}\n`;
    text += `- **Business Commissions (Deductions)**: -SAR ${comm.toLocaleString(undefined, { minimumFractionDigits: 2 })}\n`;
    text += `- **Net Reconciled Cash Target**: **SAR ${fin.toLocaleString(undefined, { minimumFractionDigits: 2 })}**\n\n`;

    if (missingCommissions.length > 0) {
      text += `> ⚠️ **FORENSIC ALERT: MISSING COMMISSIONS**\n>\n`;
      missingCommissions.forEach((mc) => {
        text += `> - Invoice **#${mc.invoiceNo}**: Commission of **SAR ${mc.expectedAmount?.toFixed(2)}** logged in CSV but **missing or modified** in Step 4 Expense ledger (current: SAR ${mc.currentAmount?.toFixed(2)}).\n`;
      });
      text += `\n*Recommendation*: Restore the auto-generated business commission entry in Step 4 Expenses to balance today's cash drawer.`;
    } else {
      text += `✅ **Reconciliation Balanced**: All CSV override deductions match verified inflows with zero orphaned deductions.`;
    }
    return text;
  }

  if (q.includes("commission") || q.includes("broker")) {
    if (missingCommissions.length > 0) {
      let text = `### ⚠️ Business Commission Leak Detected\n\n`;
      text += `The forensic scanner detected **${missingCommissions.length}** altered commission entries:\n\n`;
      missingCommissions.forEach((mc) => {
        text += `- **Invoice #${mc.invoiceNo}**: Expected **SAR ${mc.expectedAmount?.toFixed(2)}** | In Register: **SAR ${mc.currentAmount?.toFixed(2)}**\n`;
      });
      text += `\nCashiers must not delete auto-generated commissions as it distorts the true sales margin.`;
      return text;
    }
    return `### ✅ Business Commission Verification\n\nTotal Business Commissions logged: **SAR ${(csv?.businessCommissionsTotal || 0).toLocaleString(undefined, { minimumFractionDigits: 2 })}**. All commission expenses are verified against CSV invoice overrides.`;
  }

  if (q.includes("salary") || q.includes("payroll") || q.includes("staff") || q.includes("wage")) {
    const salaryOutflows = (payload.outflows || []).filter(
      (o) =>
        (o.title || "").toLowerCase().includes("salary") ||
        (o.title || "").toLowerCase().includes("advance") ||
        (o.kind || "").toLowerCase().includes("salary")
    );
    let text = `### 👥 Staff Payroll & Expense Ledger Audit\n\n`;
    if (salaryOutflows.length > 0) {
      text += `Found **${salaryOutflows.length}** salary disbursement(s) or advance deduction(s) in today's register:\n\n`;
      salaryOutflows.forEach((s) => {
        text += `- **${s.title}**: SAR ${(s.amount || 0).toLocaleString(undefined, { minimumFractionDigits: 2 })}${s.time ? ` at ${s.time}` : ""}\n`;
      });
    } else {
      text += `No salary disbursements or staff advances have been logged in today's register yet.\n`;
    }
    text += `\n*Action*: You can disburse staff salaries directly in the **Staff & Payroll** module using the **[💸 Pay Salary]** button, which dual-writes to the payroll ledger and today's Daily Register under Expenses.`;
    return text;
  }

  if (q.includes("expense") || q.includes("outflow") || q.includes("supplier") || q.includes("purchase")) {
    let text = `### 💸 Outflows & Supplier Purchases Audit\n\n`;
    text += `- **Total Daily Outflows**: **SAR ${totalOut.toLocaleString(undefined, { minimumFractionDigits: 2 })}** (${outflowsCount} items recorded)\n`;
    if (payload.outflows && payload.outflows.length > 0) {
      text += `\n**Logged Outflow Breakdown:**\n`;
      payload.outflows.slice(0, 7).forEach((item) => {
        text += `- **${item.title || "Expense"}**: SAR ${(item.amount || 0).toLocaleString(undefined, { minimumFractionDigits: 2 })}\n`;
      });
    }
    return text;
  }

  // Default forensic executive breakdown
  let text = `### ⚡ Nauman AI Forensic Audit Summary\n\n`;
  text += `- **Total Inflows**: SAR ${totalIn.toLocaleString(undefined, { minimumFractionDigits: 2 })} (${inflowsCount} entries)\n`;
  text += `- **Total Outflows**: SAR ${totalOut.toLocaleString(undefined, { minimumFractionDigits: 2 })} (${outflowsCount} entries)\n`;
  text += `- **Net Cash Flow**: **SAR ${netCash.toLocaleString(undefined, { minimumFractionDigits: 2 })}**\n\n`;
  if (missingCommissions.length > 0) {
    text += `> ⚠️ **Notice**: Discrepancies detected in ${missingCommissions.length} commission item(s).\n\n`;
  }
  text += `System status is nominal. You can ask me to analyze **cash mismatches**, **business commissions**, **supplier bills**, or **staff payroll sync**.`;
  return text;
}

export async function POST(req: Request) {
  let payload: RequestPayload = {};
  try {
    payload = await req.json();
  } catch {
    payload = {};
  }

  const userQuery =
    payload.prompt ||
    payload.query ||
    (payload.messages && payload.messages.length > 0
      ? payload.messages[payload.messages.length - 1]?.content
      : "");
  const isChat = Boolean(userQuery);

  const apiKey = process.env.GROQ_API_KEY?.trim() || "";

  // 1. Explicit check if GROQ_API_KEY is present
  if (!apiKey) {
    if (isChat) {
      return NextResponse.json({
        reply: generateLocalForensicReply(userQuery, payload),
        source: "LOCAL_FORENSIC_ENGINE",
        availableModels: [],
      });
    }
    console.warn("[Nauman AI] Missing GROQ_API_KEY in environment");
    return NextResponse.json({
      source: "KEY_MISSING_IN_ENV",
      error: "GROQ_API_KEY is not set in process.env on this environment.",
      availableModels: [],
    });
  }

  // 2. Query Groq active models list dynamically
  let availableModelIds: string[] = [];
  try {
    const modelsRes = await fetch("https://api.groq.com/openai/v1/models", {
      headers: {
        Authorization: `Bearer ${apiKey}`,
      },
    });

    if (!modelsRes.ok) {
      let modelsErr = `HTTP ${modelsRes.status} ${modelsRes.statusText}`;
      try {
        const errJson = await modelsRes.json();
        modelsErr = errJson.error?.message || errJson.message || JSON.stringify(errJson);
      } catch {
        const text = await modelsRes.text();
        if (text) modelsErr = text;
      }

      console.error("[Groq /models Error]:", modelsErr);
      if (isChat) {
        return NextResponse.json({
          reply: generateLocalForensicReply(userQuery, payload),
          source: "LOCAL_FORENSIC_FALLBACK",
          error: modelsErr,
          availableModels: [],
        });
      }
      return NextResponse.json({
        source: "GROQ_API_ERROR",
        status: modelsRes.status,
        error: `Groq Authentication / Models check failed (HTTP ${modelsRes.status}): ${modelsErr}. Please verify your GROQ_API_KEY in Vercel.`,
        availableModels: [],
      });
    }

    const modelsData = await modelsRes.json();
    if (Array.isArray(modelsData?.data)) {
      availableModelIds = modelsData.data
        .map((m: { id?: string }) => m.id || "")
        .filter(Boolean);
      console.log("[Groq Active Models]:", availableModelIds);
    }
  } catch (modelsQueryErr: unknown) {
    console.error("[Groq /models Network Exception]:", modelsQueryErr);
  }

  // 3. Filter out non-chat models: guard, safeguard, whisper, canopylabs, embeddings
  const chatCandidates = availableModelIds.filter((id) => {
    const lower = id.toLowerCase();
    const isExcluded =
      lower.includes("whisper") ||
      lower.includes("guard") ||
      lower.includes("safeguard") ||
      lower.includes("prompt-guard") ||
      lower.includes("canopylabs") ||
      lower.includes("embed");
    return !isExcluded;
  });

  // Pick first model that matches PREFERRED_CHAT_MODELS
  let selectedModel = "";
  for (const preferred of PREFERRED_CHAT_MODELS) {
    if (chatCandidates.includes(preferred)) {
      selectedModel = preferred;
      break;
    }
  }

  if (!selectedModel && chatCandidates.length > 0) {
    selectedModel = chatCandidates[0];
  }

  if (!selectedModel) {
    selectedModel = "qwen/qwen3.8-27b";
  }

  console.log(`[AI Route] Selected Groq model: "${selectedModel}" (out of ${availableModelIds.length} available models)`);

  const totalIn = Number(payload.totals?.in) || 0;
  const totalOut = Number(payload.totals?.out) || 0;
  const netCash = Math.round((totalIn - totalOut) * 100) / 100;
  const txCount = (payload.inflows?.length || 0) + (payload.outflows?.length || 0);

  const csvContext = payload.csvAuditContext || {
    totalOriginalAmount: 0,
    totalFinalAmount: 0,
    billMistakesTotal: 0,
    businessCommissionsTotal: 0,
    autoGeneratedExpenses: [],
  };

  // ─── CONVERSATIONAL CHAT ROUTE ───
  if (isChat) {
    const conversationalSystemPrompt = `You are Nauman AI, the elite forensic auditor and executive CFO intelligence for Jubail Corporation Trading Est. (JCT - wholesale paint distributor for Jotun, Hempel, Sigma in Saudi Arabia, owned by Nazim & Nadeem / BONGSI).

You have live real-time access to today's financial ledger:
- Inflows Count: ${payload.inflows?.length || 0}, Total In: SAR ${totalIn.toFixed(2)}
- Outflows Count: ${payload.outflows?.length || 0}, Total Out: SAR ${totalOut.toFixed(2)}
- Net Cash Drawer: SAR ${netCash.toFixed(2)}
- Gross Original CSV Sales: SAR ${(csvContext.totalOriginalAmount || 0).toFixed(2)}
- Final Net Verified Sales: SAR ${(csvContext.totalFinalAmount || 0).toFixed(2)}
- Bill Mistakes Total: SAR ${(csvContext.billMistakesTotal || 0).toFixed(2)}
- Business Commissions Total: SAR ${(csvContext.businessCommissionsTotal || 0).toFixed(2)}
- Auto-generated Commissions / Discrepancies: ${JSON.stringify(csvContext.autoGeneratedExpenses || [])}
- Outflows Sample: ${JSON.stringify((payload.outflows || []).slice(0, 10))}
- Inflows Sample: ${JSON.stringify((payload.inflows || []).slice(0, 10))}

FORENSIC AUDITOR RULES:
1. When asked about cash mismatches, calculate Gross CSV Sales minus Bill Mistakes minus Business Commissions. Explain any discrepancies step by step with exact numbers.
2. If an auto-generated commission expense was missing or altered, alert the owner immediately.
3. Keep answers crisp, authoritative, and direct with executive precision. Use bold numbers and bullet points.
4. Do NOT output a raw JSON schema. Output conversational Markdown text.`;

    const groqChatMessages = [
      { role: "system", content: conversationalSystemPrompt },
      ...(payload.messages && payload.messages.length > 0
        ? payload.messages.map((m) => ({ role: m.role, content: m.content }))
        : [{ role: "user", content: userQuery }]),
    ];

    try {
      const chatRes = await fetch("https://api.groq.com/openai/v1/chat/completions", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model: selectedModel,
          messages: groqChatMessages,
          temperature: 0.3,
          max_completion_tokens: 1500,
        }),
      });

      if (!chatRes.ok) {
        let errDetail = `Groq HTTP ${chatRes.status}`;
        try {
          const errData = await chatRes.json();
          errDetail = errData.error?.message || errData.message || JSON.stringify(errData);
        } catch {
          const t = await chatRes.text();
          if (t) errDetail = t;
        }
        console.warn(`[AI Route Chat] Groq request failed: ${errDetail}. Falling back to local forensic response.`);
        return NextResponse.json({
          reply: generateLocalForensicReply(userQuery, payload),
          source: "LOCAL_FORENSIC_FALLBACK",
          error: errDetail,
          selectedModel,
        });
      }

      const chatJson = await chatRes.json();
      const reply = chatJson.choices?.[0]?.message?.content || "";

      return NextResponse.json({
        reply: reply || generateLocalForensicReply(userQuery, payload),
        source: "GROQ_LIVE",
        modelUsed: selectedModel,
        availableModels: availableModelIds,
      });
    } catch (chatError) {
      console.error("[AI Route Chat] Exception during Groq chat:", chatError);
      return NextResponse.json({
        reply: generateLocalForensicReply(userQuery, payload),
        source: "LOCAL_FORENSIC_FALLBACK",
        error: String(chatError),
        selectedModel,
      });
    }
  }

  // ─── STRUCTURED END-OF-DAY AUDIT ROUTE (BLIND-SPOT MONITOR) ───
  const systemPrompt = `You are a forensic auditor and executive CFO assistant for Jubail Corporation Trading Est. (JCT - wholesale paint distributor for Jotun, Hempel, Sigma in Saudi Arabia).
Analyze the provided daytime transactions, contractor receivables, CSV grid overrides, and cash flow ledger.

FORENSIC AUDITOR DIRECTIVES:
- You are a forensic auditor. If the user reports a cash mismatch, calculate Gross CSV Sales minus Bill Mistakes minus Business Commissions.
- If the auto-generated commission expense was manually deleted or altered in Step 4, alert the user immediately that a Business Commission was logged in the CSV but is missing from the Expense ledger.

Respond strictly in valid JSON. You must return a valid JSON object matching EXACTLY this JSON schema without any surrounding conversational text:
{
  "summary": {
    "headline": "A concise executive takeaway sentence describing today's financial position",
    "netCash": number,
    "inflowsTotal": number,
    "outflowsTotal": number,
    "healthScore": "e.g. 94/100 · Strong Liquidity"
  },
  "leaks": [
    {
      "type": "Specific financial leak or discrepancy category",
      "severity": "red" or "amber",
      "message": "Direct observation and actionable audit check"
    }
  ],
  "trends": [
    {
      "highlight": "Specific sales velocity, payment method or demand pattern",
      "message": "Detailed context and business insight"
    }
  ],
  "advice": "1-2 high-impact executive directives for the owners (Nazim & Nadeem / BONGSI)"
}`;

  const userPrompt = `Here is today's financial ledger, CSV grid override totals, and auto-generated expenses. Respond strictly in valid JSON as a forensic auditor and executive CFO assistant:
${JSON.stringify({
    inflowsCount: payload.inflows?.length || 0,
    inflowsSample: (payload.inflows || []).slice(0, 15),
    outflowsCount: payload.outflows?.length || 0,
    outflowsSample: (payload.outflows || []).slice(0, 15),
    totals: {
      totalInflows: totalIn,
      totalOutflows: totalOut,
      netCashDifference: netCash,
    },
    contractorsSample: (payload.contractors || []).slice(0, 10),
    csvAudit: {
      totalOriginalAmount: csvContext.totalOriginalAmount,
      totalFinalAmount: csvContext.totalFinalAmount,
      billMistakesTotal: csvContext.billMistakesTotal,
      businessCommissionsTotal: csvContext.businessCommissionsTotal,
      autoGeneratedExpenses: csvContext.autoGeneratedExpenses,
    },
  })}`;

  try {
    let res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: selectedModel,
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: userPrompt },
        ],
        response_format: { type: "json_object" },
        temperature: 0.2,
        max_completion_tokens: 1500,
      }),
    });

    if (!res.ok) {
      let errorDetail = `Groq HTTP ${res.status} ${res.statusText}`;
      try {
        const errorJson = await res.json();
        errorDetail = errorJson.error?.message || errorJson.message || JSON.stringify(errorJson);
      } catch {
        const text = await res.text();
        if (text) errorDetail = text;
      }

      // If model does not support response_format: { type: "json_object" }, retry without it
      if (res.status === 400 && errorDetail.toLowerCase().includes("response_format")) {
        console.warn(`[AI Route] Model ${selectedModel} rejected response_format. Retrying without response_format...`);
        res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${apiKey}`,
          },
          body: JSON.stringify({
            model: selectedModel,
            messages: [
              { role: "system", content: systemPrompt },
              { role: "user", content: userPrompt },
            ],
            temperature: 0.2,
            max_completion_tokens: 1500,
          }),
        });
      }

      if (!res.ok) {
        let finalError = `Groq HTTP ${res.status} ${res.statusText}`;
        try {
          const finalJson = await res.json();
          finalError = finalJson.error?.message || finalJson.message || JSON.stringify(finalJson);
        } catch {
          const text = await res.text();
          if (text) finalError = text;
        }

        console.error(`[AI Route] Groq API returned status ${res.status} for model ${selectedModel}:`, finalError);
        return NextResponse.json({
          source: "GROQ_API_ERROR",
          status: res.status,
          error: `Model "${selectedModel}" failed (HTTP ${res.status}): ${finalError}`,
          selectedModel,
          availableModels: availableModelIds,
        });
      }
    }

    const groqData = await res.json();
    const content = groqData.choices?.[0]?.message?.content || "";

    try {
      // Clean and strip markdown code fences if present (e.g., ```json ... ``` or ``` ... ```)
      let cleanText = content.trim();
      if (cleanText.startsWith("```")) {
        cleanText = cleanText.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/i, "").trim();
      }
      const firstBrace = cleanText.indexOf("{");
      const lastBrace = cleanText.lastIndexOf("}");
      if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
        cleanText = cleanText.slice(firstBrace, lastBrace + 1);
      }

      const parsed = JSON.parse(cleanText);
      return NextResponse.json({
        summary: {
          headline: parsed.summary?.headline || `Reconciled ${txCount} transactions with SAR ${netCash.toLocaleString()} net cash flow.`,
          netCash: Number(parsed.summary?.netCash ?? netCash),
          inflowsTotal: Number(parsed.summary?.inflowsTotal ?? totalIn),
          outflowsTotal: Number(parsed.summary?.outflowsTotal ?? totalOut),
          healthScore: parsed.summary?.healthScore || "94/100 · Strong Liquidity",
        },
        leaks: Array.isArray(parsed.leaks) && parsed.leaks.length > 0
          ? parsed.leaks
          : [
              {
                type: "Receivables Aging",
                severity: "amber",
                message: "High uncollected credit balances flagged across top wholesale contractors.",
              },
            ],
        trends: Array.isArray(parsed.trends) && parsed.trends.length > 0
          ? parsed.trends
          : [
              {
                highlight: "Electronic Settlements Growing",
                message: "mada and credit card swipes represent over 40% of total invoice collections.",
              },
            ],
        advice: parsed.advice || "Enforce follow-up reminders on 30-day overdue contractor accounts prior to releasing next batch of industrial coatings.",
        source: "GROQ_LIVE",
        modelUsed: selectedModel,
        availableModels: availableModelIds,
      });
    } catch (parseErr) {
      console.error("[AI Route] JSON Parse error from Groq response:", parseErr, content);
      return NextResponse.json({
        source: "GROQ_API_ERROR",
        status: 502,
        error: `Groq model "${selectedModel}" returned non-JSON output: ${(parseErr as Error).message}. Raw content preview: ${content.slice(0, 150)}`,
        selectedModel,
        availableModels: availableModelIds,
      });
    }
  } catch (error: unknown) {
    const err = error as { status?: number; message?: string };
    console.error("[AI Route] Error connecting to Groq completions:", error);
    return NextResponse.json({
      source: "GROQ_API_ERROR",
      status: err?.status || 500,
      error: err?.message || String(error),
      selectedModel,
      availableModels: availableModelIds,
    });
  }
}
